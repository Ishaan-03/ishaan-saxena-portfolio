/**
 * Every fact here was read out of the files in certificates-raw/, not from
 * their filenames. Several filenames are wrong about what they hold: "Data
 * science certificate.pdf" is a DataScientest programming exam, and
 * "Web development , cloud and devops .pdf" is the 100xdevs full stack course.
 *
 * Rule from section 6 of the brief: a course is never called a certification.
 * "AWS Cloud Practitioner Essentials" is a training course, not the AWS
 * Certified Cloud Practitioner exam, and it is typed accordingly.
 *
 * The list is flat, in display order. The brief suggested collapsing a
 * program's courses into an expandable list, but hiding eight real Coursera
 * certificates behind one card made the section look far thinner than it is.
 * Ishaan asked for every credential to be visible, so each one is its own card
 * and `programSlug` records which program a course belongs to.
 *
 * Thumbnails and file copies are generated by `npm run certificates`.
 */

export type CredentialType = 'certificate' | 'course' | 'exam' | 'letter';

export type CredentialCategory =
  'cloud' | 'security-operations' | 'cybersecurity-foundations' | 'development';

export type Credential = {
  slug: string;
  title: string;
  /** Set only when the document's printed wording differs from the title shown. */
  printedTitle?: string;
  issuer: string;
  /** ISO date of issue, for sorting and Intl formatting per locale. */
  date: string;
  type: CredentialType;
  category: CredentialCategory;
  credentialId?: string;
  /** Only where the document prints a durable public verification link. */
  verifyUrl?: string;
  /** Anything a reader should know that the document does not say plainly. */
  note?: string;
  /** Pinned to the front of the grid. At most four, per section 6. */
  featured?: boolean;
  /** The program this course is part of, when it belongs to one. */
  programSlug?: string;
};

